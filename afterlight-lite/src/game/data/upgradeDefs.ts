export function getUpgradeDef(id: string): UpgradeDef {
  const def = UPGRADE_DEFS.find((u) => u.id === id);
  if (!def) throw new Error(`Unknown upgrade id: ${id}`);
  return def;
}

export const WEAPON_UPGRADE_IDS = UPGRADE_DEFS.filter((u) => u.category === "weapon").map((u) => u.id);
export const PASSIVE_UPGRADE_IDS = UPGRADE_DEFS.filter((u) => u.category === "passive").map((u) => u.id);
